export type PublicI18nKey = keyof typeof publicTranslations.tr

export function normalizePublicLocale(value: string | null | undefined): PublicLocale | null {
  if (!value) return null
  const normalized = value.trim().toLowerCase().replace('_', '-')
  const language = normalized.split('-')[0]

  if (language === 'tr') return 'tr'
  if (language === 'en') return 'en'
  if (language === 'de') return 'de'
  if (language === 'ru') return 'ru'
  if (language === 'ar') return 'ar'

  return null
}

export function pickPublicLocale(values: readonly string[] | null | undefined): PublicLocale {
  for (const value of values || []) {
    const locale = normalizePublicLocale(value)
    if (locale) return locale
  }
  return 'tr'
}

export function getPublicTranslation(locale: PublicLocale, key: PublicI18nKey) {
  return publicTranslations[locale][key] || publicTranslations.tr[key]
}

export function isPublicLocaleRtl(locale: PublicLocale) {
  return PUBLIC_RTL_LOCALES.has(locale)
}

export function formatPublicPrice(value: number, locale: PublicLocale) {
  return new Intl.NumberFormat(locale === 'tr' ? 'tr-TR' : locale, {
    style: 'currency',
    currency: 'TRY',
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(value)
}

export function formatPublicNumber(value: number, locale: PublicLocale) {
  return new Intl.NumberFormat(locale === 'tr' ? 'tr-TR' : locale).format(value)
}
